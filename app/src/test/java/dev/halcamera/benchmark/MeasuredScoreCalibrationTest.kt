    @Test fun frozenCoefficientsMatchMeasuredNormalRuns() {
        val actual = ScoreComposer.calibrate(normalRuns)
        val frozen = S25PlusScoreDraft.calibration
        assertEquals(frozen.normalRunIds, actual.normalRunIds)
        actual.curves.zip(frozen.curves).forEach { (a, b) ->
            assertEquals(b.metricId, a.metricId)
            assertEquals(b.center, a.center, 1e-10)
            assertEquals(b.scale, a.scale, 1e-10)
        }
    }

